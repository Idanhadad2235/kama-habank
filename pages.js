// pages.js — the Q&A page and the legal pages (terms, privacy, accessibility).
// The legal texts are drafts for the lawyer; fields in [brackets] are filled in before going live.

import { FAQ, BANK_PATHS } from "./faq.js";
import { CONFIG } from "./config.js";
import { getBackend } from "./backend.js";

const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
const fmtDate = (iso) => { const [y, m, d] = iso.split("-"); return `${Number(d)}.${Number(m)}.${y}`; };

function pageHead(title, sub) {
  return `<header class="top">
    <a href="#" class="back-link" data-action="close-page">→ חזרה</a>
    <h1 tabindex="-1">${esc(title)}</h1>
    ${sub ? `<p class="muted small">${esc(sub)}</p>` : ""}
  </header>`;
}

function sections(list) {
  return list.map((s) => `<section class="card legal">
    <h2>${esc(s.h)}</h2>
    ${(s.p || []).map((p) => `<p>${esc(p)}</p>`).join("")}
    ${s.ul ? `<ul>${s.ul.map((li) => `<li>${esc(li)}</li>`).join("")}</ul>` : ""}
  </section>`).join("");
}

const draftNote = () => (CONFIG.legalDraft ? `<div class="card note-card"><p class="small">טיוטה לבדיקה של עורך דין. הפרטים בסוגריים מרובעים יושלמו לפני שהאתר עולה.</p></div>` : "");

// ---------- Q&A ----------

export function renderFaq() {
  const canMessage = !!getBackend();
  const items = FAQ.filter((f) => canMessage || f.id !== "contact").map((f) => `<details class="card faq" id="faq-${f.id}">
    <summary><h2>${esc(f.q)}</h2></summary>
    ${f.a.map((p) => `<p>${esc(p)}</p>`).join("")}
    ${f.banks ? `<ul class="small">${BANK_PATHS.map(([b, path]) => `<li><b>${esc(b)}:</b> ${esc(path)}</li>`).join("")}</ul>` : ""}
  </details>`).join("");
  return `${pageHead("שאלות ותשובות")}
  ${items}
  ${canMessage ? `<section class="card">
    <h2>לא מצאת תשובה?</h2>
    <p class="muted">אפשר לכתוב לנו בצ'אט, ונחזור אליך.</p>
    <button type="button" class="btn primary small" data-action="open-chat">לכתוב לנו</button>
  </section>` : ""}`;
}

